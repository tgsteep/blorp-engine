// Downloads long-term monthly climatology from NASA POWER for Turkey's 81 provinces and writes
// src/core/solar/climateTR.ts (bundled in the app → works offline).
// Run: node scripts/fetch-solar-data.mjs   (Node 18+, needs internet; used by the GitHub Action)
import { mkdirSync, writeFileSync } from 'node:fs';
import { PROVINCES } from './tr-provinces.mjs';

const MONTHS = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'];
const PARAMS = ['ALLSKY_SFC_SW_DWN', 'ALLSKY_SFC_SW_DIFF', 'T2M'];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchPoint(lat, lon) {
  const url = `https://power.larc.nasa.gov/api/temporal/climatology/point?parameters=${PARAMS.join(',')}&community=RE&longitude=${lon}&latitude=${lat}&format=JSON`;
  for (let attempt = 1; attempt <= 4; attempt++) {
    const res = await fetch(url);
    if (res.ok) {
      const j = await res.json();
      const p = j?.properties?.parameter;
      if (!p) throw new Error(`unexpected response: ${JSON.stringify(j).slice(0, 300)}`);
      if (!fetchPoint.logged) { fetchPoint.logged = true; console.log(`::notice::first response keys ${Object.keys(p).join(',')} sample ${JSON.stringify(p[PARAMS[0]]).slice(0, 200)}`); }
      const row = (k) => MONTHS.map((m) => {
        const v = p[k][m];
        if (typeof v !== 'number' || v < -900) throw new Error(`missing ${k} ${m} at ${lat},${lon}`);
        return Math.round(v * 100) / 100;
      });
      return { ghi: row('ALLSKY_SFC_SW_DWN'), dhi: row('ALLSKY_SFC_SW_DIFF'), t2m: row('T2M'), header: j.header };
    }
    const body = (await res.text()).slice(0, 300).replace(/\s+/g, ' ');
    console.log(`::warning::HTTP ${res.status} for ${lat},${lon} (attempt ${attempt}): ${body}`);
    await sleep(3000 * attempt);
  }
  throw new Error(`failed ${lat},${lon}`);
}

async function main() {
const out = [];
let period = '';
for (const [name, lat, lon] of PROVINCES) {
  const d = await fetchPoint(lat, lon);
  if (!period && d.header) period = `${d.header.start ?? ''}–${d.header.end ?? ''}`;
  out.push({ name, lat, lon, ghi: d.ghi, dhi: d.dhi, t2m: d.t2m });
  console.log(name, d.ghi.join(' '));
  await sleep(400);
}

const today = new Date().toISOString().slice(0, 10);
const ts = `/**
 * GENERATED by scripts/fetch-solar-data.mjs on ${today} — do not edit by hand.
 * Source: NASA POWER (power.larc.nasa.gov), climatology ${period}, community RE.
 * Per province: monthly mean daily irradiation on a horizontal surface [kWh/m²/day]
 * (ghi = global, dhi = diffuse) and mean air temperature at 2 m [°C], JAN…DEC.
 * NASA POWER data are free to use; cite "NASA Langley Research Center (LaRC) POWER Project".
 */
export type CityClimate = { name: string; lat: number; lon: number; ghi: number[]; dhi: number[]; t2m: number[] };

export const CLIMATE_SOURCE = 'NASA POWER climatology${period ? ' ' + period : ''} (NASA LaRC POWER Project), fetched ${today}';

export const CITIES_TR: CityClimate[] = ${JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};
`;
mkdirSync(new URL('../src/core/solar/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/core/solar/climateTR.ts', import.meta.url), ts);
console.log(`wrote ${out.length} provinces`);
}

main().catch((e) => { console.log(`::error::${String(e?.stack ?? e).replace(/\n/g, ' | ').slice(0, 900)}`); process.exit(1); });
