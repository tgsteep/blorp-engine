"""Builds src/core/aero/ceaTables.ts from NASA CEA (via RocketCEA): chamber temperature, molar mass, isentropic
exponent, c*, frozen chamber transport properties (for the Bartz heat flux) and CEA shifting-equilibrium vacuum I_sp
(reference only) on a chamber-pressure × mixture-ratio grid for four liquid propellant pairs.

Needs: gfortran, `pip install rocketcea`. Run: python3 scripts/build-cea-tables.py
"""
from rocketcea.cea_obj_w_units import CEA_Obj

PC = [5, 10, 20, 40, 70, 100, 150, 200, 300]  # bar
EPS = [5, 10, 20, 40, 80, 150]
PAIRS = [
    ('kerolox', 'LOX', 'RP-1', [1.6 + 0.15 * i for i in range(13)]),
    ('methalox', 'LOX', 'CH4', [2.2 + 0.2 * i for i in range(11)]),
    ('hydrolox', 'LOX', 'LH2', [3.0 + 0.5 * i for i in range(11)]),
    ('hypergolic', 'N2O4', 'MMH', [1.2 + 0.2 * i for i in range(9)]),
]


def r4(x):
    return float(f'{float(x):.5g}')


out = ['/** GENERATED by scripts/build-cea-tables.py from NASA CEA (RocketCEA) — do not edit by hand. */',
       '/** Grid: chamber pressure pc [bar] × mixture ratio O/F. T_c [K], M [kg/kmol], k (isentropic exponent, chamber),',
       ' * cstar [m/s], mu [Pa·s], cp [J/(kg·K)], pr (frozen chamber transport), ispVac[pc][mr][eps] CEA shifting-equilibrium vacuum I_sp [s]. */',
       f'export const CEA_PC = {PC};', f'export const CEA_EPS = {EPS};',
       'export type CeaTable = { id: string; ox: string; fuel: string; mr: number[]; Tc: number[][]; M: number[][]; k: number[][]; cstar: number[][]; mu: number[][]; cp: number[][]; pr: number[][]; ispVac: number[][][] };',
       'export const CEA: CeaTable[] = [']
for pid, ox, fu, mrs in PAIRS:
    c = CEA_Obj(oxName=ox, fuelName=fu, pressure_units='bar', temperature_units='K', isp_units='sec', cstar_units='m/s',
                specific_heat_units='J/kg-K', viscosity_units='poise')
    T, M, K, CS, MU, CP, PR, ISP = [], [], [], [], [], [], [], []
    for pc in PC:
        t, m, k, cs, mu, cp, pr, isp = [], [], [], [], [], [], [], []
        for mr in mrs:
            t.append(r4(c.get_Tcomb(Pc=pc, MR=mr)))
            mw, g = c.get_Chamber_MolWt_gamma(Pc=pc, MR=mr, eps=10)
            m.append(r4(mw)); k.append(r4(g))
            cs.append(r4(c.get_Cstar(Pc=pc, MR=mr)))
            cpf, visc, _cond, prf = c.get_Chamber_Transport(Pc=pc, MR=mr, eps=10, frozen=1)
            mu.append(r4(visc * 0.1)); cp.append(r4(cpf)); pr.append(r4(prf))
            isp.append([r4(c.get_Isp(Pc=pc, MR=mr, eps=e)) for e in EPS])
        T.append(t); M.append(m); K.append(k); CS.append(cs); MU.append(mu); CP.append(cp); PR.append(pr); ISP.append(isp)
    out.append(f"  {{ id: '{pid}', ox: '{ox}', fuel: '{fu}', mr: {[round(x, 3) for x in mrs]}, Tc: {T}, M: {M}, k: {K}, cstar: {CS}, mu: {MU}, cp: {CP}, pr: {PR}, ispVac: {ISP} }},")
    print(pid, 'done')
out.append('];\n')
open('src/core/aero/ceaTables.ts', 'w').write('\n'.join(out))
