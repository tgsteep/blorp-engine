"""
Property tables for the cycle tools, generated once from CoolProp (reference equations of state:
IAPWS-95 for water, Tillner-Roth & Baehr for R-134a, ...).   pip install CoolProp && python scripts/build-thermo-tables.py

Units in the tables: T °C, p kPa, v m³/kg, h kJ/kg, s kJ/(kg·K).
Water: IAPWS reference (u = s = 0 for saturated liquid at the triple point) = steam tables.
Refrigerants: ASHRAE reference (h = s = 0 for saturated liquid at −40 °C), as in Çengel's tables.
Superheated vapour: rows per pressure, columns = superheat ΔT above T_sat(p).
"""
import json, numpy as np
import CoolProp.CoolProp as CP

def P(o, a, x, b, y, f):
    return CP.PropsSI(o, a, x, b, y, f)

def sat_table(fluid, Ts, ref):
    rows = []
    for Tc in Ts:
        T = Tc + 273.15
        p = P('P', 'T', T, 'Q', 0, fluid) / 1e3
        vf = 1 / P('D', 'T', T, 'Q', 0, fluid); vg = 1 / P('D', 'T', T, 'Q', 1, fluid)
        hf = P('H', 'T', T, 'Q', 0, fluid) / 1e3 - ref[0]; hg = P('H', 'T', T, 'Q', 1, fluid) / 1e3 - ref[0]
        sf = P('S', 'T', T, 'Q', 0, fluid) / 1e3 - ref[1]; sg = P('S', 'T', T, 'Q', 1, fluid) / 1e3 - ref[1]
        rows.append([round(Tc, 3), round(p, 5 if p < 10 else 3), float(f'{vf:.6g}'), float(f'{vg:.6g}'), round(hf, 3), round(hg, 3), round(sf, 5), round(sg, 5)])
    return rows

def sup_table(fluid, ps, dTs, ref):
    out = []
    for p in ps:
        Ts = P('T', 'P', p * 1e3, 'Q', 1, fluid)
        hs, ss = [], []
        for dT in dTs:
            T = Ts + dT if dT > 0 else Ts
            if dT == 0:
                h = P('H', 'P', p * 1e3, 'Q', 1, fluid); s = P('S', 'P', p * 1e3, 'Q', 1, fluid)
            else:
                h = P('H', 'P', p * 1e3, 'T', T, fluid); s = P('S', 'P', p * 1e3, 'T', T, fluid)
            hs.append(round(h / 1e3 - ref[0], 2)); ss.append(round(s / 1e3 - ref[1], 5))
        out.append({'p': p, 'h': hs, 's': ss})
    return out

def ashrae_ref(fluid):
    T = 233.15
    return (P('H', 'T', T, 'Q', 0, fluid) / 1e3, P('S', 'T', T, 'Q', 0, fluid) / 1e3)

data = {}
# water
Tw = [0.01] + list(range(1, 371)) + [372, 373, 373.9]
pw = [1, 2, 3, 5, 7.5, 10, 15, 20, 30, 50, 75, 100, 150, 200, 300, 500, 750, 1000, 1500, 2000, 3000, 4000, 5000, 6000, 7000, 8000, 9000, 10000, 12500, 15000, 17500, 20000, 21000]
dTw = [0, 1, 2, 5, 10, 15, 20, 30, 40, 50, 60, 80, 100, 125, 150, 175, 200, 250, 300, 350, 400, 450, 500, 550, 600, 650, 700]
data['water'] = {'name': 'Water (steam)', 'Tcrit': 373.946, 'sat': sat_table('Water', Tw, (0, 0)), 'dT': dTw, 'sup': sup_table('Water', pw, dTw, (0, 0))}
# refrigerants
for key, fluid, name, Tmax in [('R134a', 'R134a', 'R-134a', 95), ('R1234yf', 'R1234yf', 'R-1234yf', 90), ('R290', 'n-Propane', 'R-290 (propane)', 90), ('R717', 'Ammonia', 'R-717 (ammonia)', 100)]:
    ref = ashrae_ref(fluid)
    Ts = list(range(-50, Tmax + 1))
    pmin = P('P', 'T', 223.15, 'Q', 0, fluid) / 1e3; pmax = P('P', 'T', 273.15 + Tmax - 3, 'Q', 0, fluid) / 1e3
    ps = [round(float(x), 2) for x in np.geomspace(pmin * 1.02, pmax, 22)]
    dTs = [0, 1, 2, 5, 10, 15, 20, 25, 30, 40, 50, 60, 70, 80, 100]
    data[key] = {'name': name, 'Tcrit': round(P('Tcrit', '', 0, '', 0, fluid) - 273.15, 2), 'sat': sat_table(fluid, Ts, ref), 'dT': dTs, 'sup': sup_table(fluid, ps, dTs, ref)}

with open('src/core/thermo/tables.ts', 'w') as f:
    f.write('// GENERATED by scripts/build-thermo-tables.py from CoolProp — do not edit.\n')
    f.write('// sat rows: [T °C, p kPa, v_f, v_g m³/kg, h_f, h_g kJ/kg, s_f, s_g kJ/(kg·K)]; sup: rows per p [kPa], columns = superheat dT [K].\n')
    f.write('export type FluidTable = { name: string; Tcrit: number; sat: number[][]; dT: number[]; sup: { p: number; h: number[]; s: number[] }[] };\n')
    f.write('export const TABLES: Record<string, FluidTable> = ' + json.dumps(data, separators=(',', ':')) + ';\n')
