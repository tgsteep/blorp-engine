#!/usr/bin/env python3
"""
Builds src/core/wind/nrel5mw.ts (GENERATED) from the NREL 5-MW reference turbine files of OpenFAST r-test
(https://github.com/OpenFAST/r-test, Apache-2.0): AeroDyn blade definition + the seven airfoil polars and shapes.

  git clone --depth 1 --filter=blob:none --sparse https://github.com/OpenFAST/r-test.git /tmp/rtest
  cd /tmp/rtest && git sparse-checkout set --no-cone 'glue-codes/openfast/5MW_Baseline/Airfoils/*' \
      'glue-codes/openfast/5MW_Baseline/*AeroDyn*blade*'
  python3 scripts/build-wind-airfoils.py /tmp/rtest/glue-codes/openfast/5MW_Baseline
"""
import math, os, re, sys

base = sys.argv[1]
AF = [('Cylinder1', 1.0), ('Cylinder2', 1.0), ('DU40_A17', 0.405), ('DU35_A17', 0.35), ('DU30_A17', 0.30),
      ('DU25_A17', 0.25), ('DU21_A17', 0.21), ('NACA64_A17', 0.18)]


def num_lines(path):
    with open(path) as f:
        return [l for l in f.read().splitlines() if l.strip() and not l.strip().startswith('!')]


def polar(name):
    lines = open(os.path.join(base, 'Airfoils', name + '.dat')).read().splitlines()
    i = next(k for k, l in enumerate(lines) if 'NumAlf' in l)
    n = int(lines[i].split()[0])
    rows = [l.split() for l in lines[i + 1:] if l.strip() and not l.strip().startswith('!')][:n]
    return [(float(r[0]), float(r[1]), float(r[2])) for r in rows]


def shape(name, n=72):
    rows = num_lines(os.path.join(base, 'Airfoils', name + '_coords.txt'))
    pts = [tuple(map(float, r.split()[:2])) for r in rows[1:]]  # first line: count, then the reference point
    pts = pts[1:]
    # resample evenly by arc length (trailing edge → upper side → leading edge → lower side)
    s = [0.0]
    for a, b in zip(pts, pts[1:]):
        s.append(s[-1] + math.hypot(b[0] - a[0], b[1] - a[1]))
    L = s[-1]
    out = []
    for k in range(n):
        t = L * k / (n - 1)
        j = max(0, min(len(s) - 2, next((q for q in range(len(s) - 1) if s[q + 1] >= t), len(s) - 2)))
        f = 0 if s[j + 1] == s[j] else (t - s[j]) / (s[j + 1] - s[j])
        out.append((pts[j][0] + f * (pts[j + 1][0] - pts[j][0]), pts[j][1] + f * (pts[j + 1][1] - pts[j][1])))
    return out


blade = []
for l in num_lines(os.path.join(base, 'NRELOffshrBsline5MW_AeroDyn_blade.dat')):
    p = l.split()
    if len(p) >= 7 and re.match(r'^-?\d', p[0]):
        try:
            blade.append((float(p[0]), float(p[4]), float(p[5]), int(p[6])))
        except ValueError:
            pass
blade = blade[:19]  # the 19 nodes (the commented duplicate tip line is dropped)

out = ['/**', ' * GENERATED by scripts/build-wind-airfoils.py — do not edit.',
       ' * NREL 5-MW reference wind turbine (Jonkman et al. 2009, NREL/TP-500-38060): AeroDyn blade definition and airfoil',
       ' * tables (DOWEC data, corrected for rotational augmentation and Viterna-extrapolated by J. Jonkman), from OpenFAST r-test',
       ' * (github.com/OpenFAST/r-test, Apache License 2.0). Shapes resampled to 72 points.', ' */', '',
       'export type Airfoil = { name: string; tc: number; alpha: number[]; cl: number[]; cd: number[]; shape: [number, number][] };',
       '/** Blade nodes: span from the blade root (hub radius 1.5 m) [m], twist [deg], chord [m], airfoil index (0-based). */',
       'export const NREL5MW_BLADE: [number, number, number, number][] = [']
for s, tw, c, af in blade:
    out.append(f'  [{s:.4f}, {tw:.3f}, {c:.3f}, {af - 1}],')
out.append('];')
out.append('export const AIRFOILS: Airfoil[] = [')
for name, tc in AF:
    pol = polar(name)
    sh = shape(name)
    out.append(f"  {{ name: '{name.replace('_A17', '')}', tc: {tc}, alpha: [{', '.join(f'{a:g}' for a, _, _ in pol)}],")
    out.append(f"    cl: [{', '.join(f'{c:g}' for _, c, _ in pol)}],")
    out.append(f"    cd: [{', '.join(f'{d:g}' for _, _, d in pol)}],")
    out.append(f"    shape: [{', '.join(f'[{x:.4f}, {y:.4f}]' for x, y in sh)}] }},")
out.append('];')
dst = os.path.join(os.path.dirname(__file__), '..', 'src', 'core', 'wind', 'nrel5mw.ts')
open(dst, 'w').write('\n'.join(out) + '\n')
print('wrote', dst, len(blade), 'nodes')
